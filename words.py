def _dedupe(raw: Iterable[Dict[str, str]]) -> List[Dict[str, str]]:
    seen = set()
    out: List[Dict[str, str]] = []
    for item in raw:
        word = (item.get("kelime") or "").strip()
        hint = (item.get("ipucu") or "").strip()
        if not word or not hint:
            continue
        if hint not in GENEL_IPUCLARI:
            raise ValueError(
                f"Cok detayli ipucu: {word!r} -> {hint!r}. Izin verilenler: {GENEL_IPUCLARI}"
            )
        key = tr_lower(word)
        if key in seen:
            continue
        seen.add(key)
        out.append({"kelime": word, "ipucu": hint})
    return out


WORDS: List[Dict[str, str]] = _dedupe(_RAW_WORDS)

CATEGORIES: List[str] = sorted({entry["ipucu"] for entry in WORDS})


def pick_word(exclude: Optional[Iterable[Any]] = None) -> Dict[str, str]:
    """Havuzdan rastgele bir {"kelime": ..., "ipucu": ...} kaydi secer."""
    excluded = set()
    for item in exclude or []:
        if isinstance(item, dict):
            excluded.add(tr_lower(str(item.get("kelime", ""))))
        else:
            excluded.add(tr_lower(str(item)))
    pool = [entry for entry in WORDS if tr_lower(entry["kelime"]) not in excluded]
    if not pool:
        pool = WORDS
    return dict(random.choice(pool))


